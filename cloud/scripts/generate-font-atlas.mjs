// Build-time only: rasterize the OFL-licensed Roboto font into small glyphs.
// The Worker ships the generated atlas, not a font engine or a font fetch.
import { readFile, writeFile } from "node:fs/promises";
import { Resvg } from "@resvg/resvg-js";
import { PNG } from "pngjs";
import prettier from "prettier";

const font = await readFile(
  new URL(
    "../node_modules/@fontsource/roboto/files/roboto-latin-400-normal.woff",
    import.meta.url,
  ),
);
const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,:-/+?()= ";
const sizes = [16, 20, 34];
const atlas = {};

for (const size of sizes) {
  const columns = 12;
  const cellWidth = Math.ceil(size * 1.5) + 10;
  const cellHeight = Math.ceil(size * 1.5) + 10;
  const rows = Math.ceil(chars.length / columns);
  const padding = 4;
  const baseline = size + 6;
  const textTop = Math.round(size * 0.25) + 4;
  const glyphs = [...chars]
    .map((char, index) => {
      if (char === " ") return "";
      const x = (index % columns) * cellWidth + padding;
      const y = Math.floor(index / columns) * cellHeight + baseline;
      return `<text x="${x}" y="${y}" font-family="Roboto" font-size="${size}" fill="#ffffff">${char}</text>`;
    })
    .join("");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${columns * cellWidth}" height="${rows * cellHeight}">${glyphs}</svg>`;
  const rendered = new Resvg(svg, {
    font: {
      fontBuffers: [font],
      loadSystemFonts: false,
      defaultFontFamily: "Roboto",
    },
  }).render();
  const image = PNG.sync.read(rendered.asPng());
  const result = {};
  for (let index = 0; index < chars.length; index++) {
    const char = chars[index];
    if (char === " ") {
      result[char] = {
        x: 0,
        y: 0,
        w: 0,
        h: 0,
        advance: Math.round(size * 0.34),
        data: "",
      };
      continue;
    }
    const left = (index % columns) * cellWidth;
    const top = Math.floor(index / columns) * cellHeight;
    let minX = cellWidth,
      minY = cellHeight,
      maxX = -1,
      maxY = -1;
    for (let y = 0; y < cellHeight; y++)
      for (let x = 0; x < cellWidth; x++) {
        const alpha = image.data[((top + y) * image.width + left + x) * 4 + 3];
        if (!alpha) continue;
        minX = Math.min(minX, x);
        minY = Math.min(minY, y);
        maxX = Math.max(maxX, x);
        maxY = Math.max(maxY, y);
      }
    if (maxX < 0) throw new Error(`Font did not render: ${char}`);
    const w = maxX - minX + 1,
      h = maxY - minY + 1,
      packed = Buffer.alloc(Math.ceil((w * h) / 2));
    for (let y = 0; y < h; y++)
      for (let x = 0; x < w; x++) {
        const alpha =
          image.data[
            ((top + minY + y) * image.width + left + minX + x) * 4 + 3
          ];
        const level = Math.round(alpha / 17);
        const pixel = y * w + x;
        packed[pixel >> 1] |= pixel & 1 ? level : level << 4;
      }
    result[char] = {
      x: minX - padding,
      y: minY - textTop,
      w,
      h,
      advance: Math.max(Math.round(size * 0.22), maxX - padding + 3),
      data: packed.toString("base64"),
    };
  }
  atlas[size] = result;
}

const source = `// Generated by scripts/generate-font-atlas.mjs from Roboto (SIL OFL 1.1).\nexport default ${JSON.stringify(atlas)};\n`;
await writeFile(
  new URL("../src/font-atlas.js", import.meta.url),
  await prettier.format(source, { parser: "babel" }),
);
console.log("Generated antialiased Roboto glyph atlas.");
